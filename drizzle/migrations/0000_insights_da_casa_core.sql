-- Papéis
create type public.app_role as enum ('admin', 'gestor', 'colaborador');

create table public.profiles (
  id uuid primary key,
  email text not null,
  nome text,
  setor text,
  created_at timestamptz not null default now()
);
grant select, insert, update on public.profiles to authenticated;
grant all on public.profiles to service_role;
alter table public.profiles enable row level security;

create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  role public.app_role not null default 'colaborador',
  created_at timestamptz not null default now(),
  unique (user_id, role)
);
grant select, insert on public.user_roles to authenticated;
grant all on public.user_roles to service_role;
alter table public.user_roles enable row level security;

create or replace function public.has_role(_user_id uuid, _role public.app_role)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles where user_id = _user_id and role = _role
  )
$$;

create policy "profiles: ver o proprio" on public.profiles
for select to authenticated using (id = auth.uid() or public.has_role(auth.uid(), 'admin'));
create policy "profiles: criar o proprio" on public.profiles
for insert to authenticated with check (id = auth.uid());
create policy "profiles: editar o proprio" on public.profiles
for update to authenticated using (id = auth.uid() or public.has_role(auth.uid(), 'admin'));

create policy "roles: ver" on public.user_roles
for select to authenticated using (user_id = auth.uid() or public.has_role(auth.uid(), 'admin'));
create policy "roles: auto-cadastro colaborador" on public.user_roles
for insert to authenticated with check (user_id = auth.uid() and role = 'colaborador');

-- Feedbacks de clientes
create table public.feedback_clientes (
  id bigint generated by default as identity primary key,
  cliente_email text,
  categoria text,
  nota integer not null check (nota between 1 and 10),
  feedback_texto text,
  tags text[] not null default '{}',
  data_envio date not null default current_date,
  created_at timestamptz not null default now()
);
grant select, insert, update, delete on public.feedback_clientes to authenticated;
grant usage, select on sequence public.feedback_clientes_id_seq to authenticated;
grant all on public.feedback_clientes to service_role;
alter table public.feedback_clientes enable row level security;

create policy "clientes: todos autenticados leem" on public.feedback_clientes
for select to authenticated using (true);
create policy "clientes: admin insere" on public.feedback_clientes
for insert to authenticated with check (public.has_role(auth.uid(), 'admin'));
create policy "clientes: admin atualiza" on public.feedback_clientes
for update to authenticated using (public.has_role(auth.uid(), 'admin'));
create policy "clientes: admin remove" on public.feedback_clientes
for delete to authenticated using (public.has_role(auth.uid(), 'admin'));

-- Feedbacks internos
create table public.feedback_interno (
  id bigint generated by default as identity primary key,
  colaborador_id uuid,
  setor text not null,
  anonimo boolean not null default false,
  nota_lideranca integer check (nota_lideranca between 1 and 10),
  nota_ambiente integer check (nota_ambiente between 1 and 10),
  nota_processos integer check (nota_processos between 1 and 10),
  nota_comunicacao integer check (nota_comunicacao between 1 and 10),
  feedback_texto text,
  data_envio date not null default current_date,
  created_at timestamptz not null default now()
);
grant select, insert, update, delete on public.feedback_interno to authenticated;
grant usage, select on sequence public.feedback_interno_id_seq to authenticated;
grant all on public.feedback_interno to service_role;
alter table public.feedback_interno enable row level security;

create policy "interno: admin e gestor leem" on public.feedback_interno
for select to authenticated using (
  public.has_role(auth.uid(), 'admin') or public.has_role(auth.uid(), 'gestor')
);
create policy "interno: autenticado responde" on public.feedback_interno
for insert to authenticated with check (
  colaborador_id is null or colaborador_id = auth.uid()
);
create policy "interno: admin remove" on public.feedback_interno
for delete to authenticated using (public.has_role(auth.uid(), 'admin'));

